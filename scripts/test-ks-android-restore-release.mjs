import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadApprovedAndroidApk, androidRelease } from './ks-android-restore-release.mjs';
const apk = await loadApprovedAndroidApk();
assert.equal(androidRelease.versionCode, 2026102602);
assert.equal(apk.length, 84593786);
assert.equal(createHash('sha256').update(apk).digest('hex'), '52d1094ef9a57f8dec4651eefc83c66d399a7a3ab8628713b74bb16abebbe436');
if (process.argv.includes('--built')) assert.deepEqual(await readFile(new URL('../dist/downloads/KristalStreams-Restore.apk', import.meta.url)), apk);
console.log('PASS: separate recovery download exactly matches the owner-signed rollback APK; physical artwork loading still requires device validation');
